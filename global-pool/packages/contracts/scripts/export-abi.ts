/**
 * Exports the GlobalPoolRounds ABI after `forge build`:
 *   abi/GlobalPoolRounds.json  plain JSON ABI (any language / tool)
 *   abi/GlobalPoolRounds.ts    `as const` ABI for viem (full type inference)
 * Run via `pnpm --filter @gp/contracts build` (or `abi` after a manual `forge build`).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { formatJson } from './lib/format.ts';
import * as prettier from 'prettier';

const root = new URL('../', import.meta.url);
const artifactPath = fileURLToPath(new URL('out/GlobalPoolRounds.sol/GlobalPoolRounds.json', root));
const jsonOut = fileURLToPath(new URL('abi/GlobalPoolRounds.json', root));
const tsOut = fileURLToPath(new URL('abi/GlobalPoolRounds.ts', root));

const artifact = JSON.parse(await readFile(artifactPath, 'utf8')) as { abi?: unknown[] };
if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
  throw new Error(`no ABI in ${artifactPath}; run forge build first`);
}

await writeFile(jsonOut, await formatJson(artifact.abi, jsonOut));

const ts = `/**
 * GlobalPoolRounds ABI — GENERATED by scripts/export-abi.ts from the Foundry artifact. Do not edit.
 * Usage (viem): \`getContract({ address, abi: globalPoolRoundsAbi, client })\`.
 */
export const globalPoolRoundsAbi = ${JSON.stringify(artifact.abi)} as const;

export type GlobalPoolRoundsAbi = typeof globalPoolRoundsAbi;
`;
const config = (await prettier.resolveConfig(tsOut)) ?? {};
await writeFile(
  tsOut,
  await prettier.format(ts, { ...config, parser: 'typescript', filepath: tsOut }),
);
console.info(`exported ${artifact.abi.length} ABI items → abi/GlobalPoolRounds.{json,ts}`);
