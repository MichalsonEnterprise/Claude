/**
 * Exports deployable LOCAL-DEVNET artifacts (ABI + creation bytecode) after `forge build`:
 *   artifacts/local-devnet.json   GlobalPoolRounds + VRFCoordinatorV2_5Mock + MockUSDT
 *
 * Consumers (the API e2e suite) deploy these on a throwaway Anvil chain to run the full round lifecycle, the deposit
 * watcher and the withdrawal broadcaster without Foundry's compiler. DEMO / testnet only: the mocks (VRF coordinator
 * with manual fulfilment, owner-mintable 6-decimal token) must never be deployed to a public network.
 * Run via `pnpm --filter @gp/contracts build` (or `artifacts` after a manual `forge build`).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { formatJson } from './lib/format.ts';

const root = new URL('../', import.meta.url);
export const LOCAL_ARTIFACTS = [
  { name: 'GlobalPoolRounds', source: 'GlobalPoolRounds.sol' },
  { name: 'VRFCoordinatorV2_5Mock', source: 'VRFCoordinatorV2_5Mock.sol' },
  { name: 'MockUSDT', source: 'MockUSDT.sol' },
] as const;
export const localArtifactsPath = fileURLToPath(new URL('artifacts/local-devnet.json', root));

interface ForgeArtifact {
  abi?: unknown[];
  bytecode?: { object?: string };
}

/** Reads the Foundry `out/` artifacts into the exported shape. */
export async function readLocalArtifacts(): Promise<
  Record<string, { abi: unknown[]; bytecode: string }>
> {
  const out: Record<string, { abi: unknown[]; bytecode: string }> = {};
  for (const { name, source } of LOCAL_ARTIFACTS) {
    const file = fileURLToPath(new URL(`out/${source}/${name}.json`, root));
    const artifact = JSON.parse(await readFile(file, 'utf8')) as ForgeArtifact;
    const bytecode = artifact.bytecode?.object;
    if (!Array.isArray(artifact.abi) || !bytecode || bytecode === '0x') {
      throw new Error(`no ABI / bytecode in ${file}; run forge build first`);
    }
    out[name] = { abi: artifact.abi, bytecode };
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const artifacts = await readLocalArtifacts();
  const doc = {
    note: 'GENERATED by scripts/export-artifacts.ts from the Foundry artifacts. LOCAL DEVNET / TESTS ONLY (Anvil). Do not edit.',
    contracts: artifacts,
  };
  await writeFile(localArtifactsPath, await formatJson(doc, localArtifactsPath));
  console.info(`exported ${Object.keys(artifacts).join(', ')} → artifacts/local-devnet.json`);
}
